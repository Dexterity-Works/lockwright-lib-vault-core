// Property-based fault schedules. A schedule is a JSON list of steps over
// peers A, B, C (optionally D) sharing one vault:
//   { op: 'write', peer, key, value, fileBytes? }   { op: 'remove', peer, key }
//   { op: 'offline' | 'online' | 'closeOpen' | 'restart' | 'lock' |
//     'unlock' | 'epoch', peer }                    { op: 'wait', ms }
//   { op: 'kick', by, target }   { op: 'rejoin', by, target }
// runSchedule runs one, heals every peer and checks the invariants;
// ddmin/minimise shrink a failing one. Entry: schedule.test.js.
//
// Known findings. Opt-in ops (generate(..., { known })): '1' adds
// swarmDestroy (Finding 1, swarm.destroy then restart), 'R1' rejoins on the
// kicked device's old store, 'L1' adds kickLock (the kicker locks mid-kick).
// Opt-in modes: runSchedule's `flush: false` drops the wait after a resume
// (F1), `settle: false` the wait for a writable base before a close (F3).
// Not generated: P1, since the generator never shares one invite between
// joiners. Generated by default and not fixed: F2 (seen once: closeOpen
// reopens on a view that went backwards, then SESSION_CLOSED) and F4 (a write that
// lands while Autobase reboots on an indexer change, SESSION_CLOSED), so a
// default seed fails on them now and then.
//
// Not covered. Faults are app-lifecycle faults only: offline is
// swarm.suspend of one peer, so there is no split between peer groups, no
// connection drop without a suspend, and no step checks its trace. A kick
// waits until the kicker holds every block of the target's writer (see
// barrier), so a kick racing the target's in-flight writes never comes up.
// The model (lastOps) accepts each writer's last op on a key, so a write
// or remove lost to another writer's later op on that key passes.

const KEYS = 8
const FILE_SIZES = [1024, 65536]
const CHECK_TIMEOUT = 60000
// Above the 30 s waits a step makes (kick barrier, pairing), below jest's.
const STEP_TIMEOUT = 75000
const TEARDOWN_TIMEOUT = 30000
const REFUSED = /Vault key (not available yet|must rotate first)/

// mulberry32, as in soak.test.js
const rng = (s) => () => {
  s = (s + 0x6d2b79f5) | 0
  let t = Math.imul(s ^ (s >>> 15), 1 | s)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}

