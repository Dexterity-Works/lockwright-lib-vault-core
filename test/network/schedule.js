/** The peers a schedule names, A, B and C at least. */
export const peersOf = (steps) =>
  [
    ...new Set([
      'A',
      'B',
      'C',
      ...steps.flatMap((s) => [s.peer, s.by, s.target].filter(Boolean))
    ])
  ].sort()

const initialState = (peers) => ({
  peers: Object.fromEntries(
    peers.map((id) => [id, { member: true, open: true, online: true }])
  ),
  kicked: null,
  written: new Set(),
  epoch: false
})

// Preconditions: a member with its vault open writes, removes a key some
// step wrote, drops or reconnects; kick and rejoin need both ends reachable,
// one kicked device at a time, and nobody kicks itself.
const allowed = (state, s) => {
  const p = (id) => state.peers[id]
  const ready = (id) => !!p(id)?.member && p(id).open
  const reachable = (id) => ready(id) && p(id).online
  switch (s.op) {
    case 'write':
    case 'epoch':
    case 'closeOpen':
    case 'restart':
    case 'lock':
    case 'swarmDestroy':
      return ready(s.peer)
    case 'remove':
      return ready(s.peer) && state.written.has(s.key)
    case 'offline':
      return reachable(s.peer)
    case 'online':
      return ready(s.peer) && !p(s.peer).online
    case 'unlock':
      return !!p(s.peer)?.member && !p(s.peer).open
    case 'kick':
    case 'kickLock':
      return (
        state.kicked === null &&
        s.by !== s.target &&
        reachable(s.by) &&
        reachable(s.target)
      )
    case 'rejoin':
      return !!s.target && state.kicked === s.target && reachable(s.by)
    case 'wait':
      return s.ms >= 0 && s.ms <= 500
    default:
      return false
  }
}

const apply = (state, s) => {
  const p = state.peers[s.peer ?? s.target]
  switch (s.op) {
    case 'write':
      state.written.add(s.key)
      break
    case 'offline':
      p.online = false
      break
    case 'online':
    case 'closeOpen':
    case 'restart':
    case 'swarmDestroy':
      p.online = true
      break
    case 'lock':
      p.open = false
      break
    case 'unlock':
      p.open = true
      p.online = true
      break
    case 'kick':
    case 'kickLock':
      p.member = false
      state.kicked = s.target
      state.epoch = true
      break
    case 'rejoin':
      p.member = true
      p.online = true
      state.kicked = null
      break
    case 'epoch':
      state.epoch = true
      break
  }
}

/** The state after `steps`, and the steps whose preconditions held. */
const simulate = (steps, peers = peersOf(steps)) => {
  const state = initialState(peers)
  const kept = []
  for (const step of steps) {
    if (!allowed(state, step)) continue
    apply(state, step)
    kept.push(step)
  }
  return { state, steps: kept }
}

/** Drop the steps a shrink left without their preconditions. */
export const normalise = (steps, peers) => simulate(steps, peers).steps

/**
 * `steps` valid steps from `seed`. `known` lists findings whose ops may be
 * generated: '1', 'R1', 'L1'.
 * @param {number} seed
 * @param {{ steps?: number, peers?: string[], known?: string[] }} [options]
 */
export const generate = (
  seed,
  { steps = 15, peers = ['A', 'B', 'C'], known = [] } = {}
) => {
  const random = rng(seed)
  const pick = (list) => list[Math.floor(random() * list.length)]
  const ops = [
    ['write', 30],
    ['remove', 6],
    ['offline', 8],
    ['online', 8],
    ['closeOpen', 4],
    ['restart', 4],
    ['lock', 3],
    ['unlock', 8],
    ['kick', 7],
    ['rejoin', 6],
    ['epoch', 3],
    ['wait', 6],
    ...(known.includes('1') ? [['swarmDestroy', 3]] : []),
    ...(known.includes('L1') ? [['kickLock', 3]] : [])
  ]
  const total = ops.reduce((sum, [, w]) => sum + w, 0)
  const chooseOp = () => {
    let roll = random() * total
    for (const [op, w] of ops) {
      roll -= w
      if (roll < 0) return op
    }
    return 'wait'
  }
  const state = initialState(peers)
  const out = []
  while (out.length < steps) {
    const op = chooseOp()
    const peer = pick(peers)
    const other = pick(peers)
    const key = `note/${Math.floor(random() * KEYS)}`
    const n = out.length
    const build = {
      write: () => ({
        op,
        peer,
        key,
        value: { k: key, n, by: peer },
        ...(random() < 0.1 ? { fileBytes: pick(FILE_SIZES) } : {})
      }),
      remove: () => ({ op, peer, key }),
      kick: () => ({ op, by: peer, target: other }),
      kickLock: () => ({ op, by: peer, target: other }),
      rejoin: () => ({
        op,
        by: peer,
        target: state.kicked,
        ...(known.includes('R1') ? { sameStore: true } : {})
      }),
      epoch: () => (state.epoch ? null : { op, peer }),
      wait: () => ({ op, ms: Math.floor(random() * 500) })
    }[op]
    const step = build ? build() : { op, peer }
    if (step && allowed(state, step)) {
      apply(state, step)
      out.push(step)
    }
  }
  return out
}

/**
 * Delta debugging (Zeller's ddmin) over `items`: the smallest subsequence
 * for which `fails` still resolves true, 1-minimal unless the budget ran
 * out. `key` maps a candidate to a cache key, so equal candidates run once.
 * @template T
 * @param {T[]} items a failing input
 * @param {(candidate: T[]) => Promise<boolean>} fails
 * @param {{ maxRuns?: number, deadline?: number, key?: (c: T[]) => string }} [options]
 * @returns {Promise<{ steps: T[], runs: number, exhausted: boolean }>}
 */
export const ddmin = async (
  items,
  fails,
  { maxRuns = Infinity, deadline = Infinity, key = null } = {}
) => {
  const seen = new Map()
  let runs = 0
  let exhausted = false
  const test = async (candidate) => {
    const k = key ? key(candidate) : undefined
    if (seen.has(k)) return seen.get(k)
    if (runs >= maxRuns || Date.now() >= deadline) {
      exhausted = true
      return false
    }
    runs++
    const result = await fails(candidate)
    if (k !== undefined) seen.set(k, result)
    return result
  }
  const split = (list, n) =>
    Array.from({ length: n }, (_, i) =>
      list.slice(
        Math.floor((i * list.length) / n),
        Math.floor(((i + 1) * list.length) / n)
      )
    )
  let current = items
  let n = 2
  while (current.length >= 2 && !exhausted) {
    const chunks = split(current, n)
    let next = null
    for (const chunk of chunks) {
      if (await test(chunk)) {
        next = chunk
        n = 2
        break
      }
    }
    // With two chunks each complement is the other chunk.
    for (let i = 0; !next && n > 2 && i < chunks.length; i++) {
      const complement = chunks.filter((_, j) => j !== i).flat()
      if (await test(complement)) {
        next = complement
        n = Math.max(n - 1, 2)
      }
    }
    if (next) {
      current = next
      continue
    }
    if (n >= current.length) break
    n = Math.min(n * 2, current.length)
  }
  return { steps: current, runs, exhausted }
}

const describeStep = (s) =>
  [
    s.op,
    ...Object.entries(s)
      .filter(([k]) => k !== 'op' && k !== 'value')
      .map(([k, v]) => `${k}=${v}`)
  ].join(' ')

const fileFor = (step) => Buffer.alloc(step.fileBytes, (step.value.n % 250) + 1)

/** How many blocks `peer` holds of the writer core `writerKey` (hex). */
const writerLength = async (peer, writerKey) => {
  const core = peer.instance.store.get({ key: Buffer.from(writerKey, 'hex') })
  await core.ready()
  const { length } = core
  await core.close()
  return length
}

// Kick only once the kicker holds every block the target appended, so the
// removal follows all of the target's writes and none of them is dropped.
const barrier = async (by, target) => {
  await waitFor(
    async () => (await by.devices()).some((d) => d?.id === target.deviceId),
    { label: `${by.id} holds ${target.id}'s device row` }
  )
  const length = target.instance.base.local.length
  await waitFor(
    async () => (await writerLength(by, target.writerKey)) >= length,
    { label: `${by.id} holds all ${length} blocks of ${target.id}'s writer` }
  )
  await by.instance.base.update()
}

// Finding F1: peers that resume within one discovery round of each other,
// with nobody else online, do not reconnect (none in 40 s). Unless `flush`
// is off, a resume waits for its discovery round before the next step.
const goOnline = async (peer, log) => {
  await peer.goOnline()
  if (log.flush) await peer.instance.swarm.flush()
}

// Finding F3: a vault closed while its Autobase is not writable for a moment
// (C applying A's first rotation) reopens not writable, never advances, and
// every write on it hangs. Unless `settle` is off, a close, restart or lock
// first waits (up to 30 s) for the base to be writable.
const settle = async (peer, log) => {
  if (!log.settle) return
  await waitFor(() => peer.instance.base.writable, {
    interval: 10,
    label: `${peer.id} is writable before it closes`
  }).catch(() => peer.trace('schedule.unsettled'))
}

const write = async (peer, step, i, log) => {
  const { epoch } = await peer.epochStatus()
  const file = step.fileBytes ? fileFor(step) : undefined
  await peer.add(step.key, step.value, file, file && 'blob.bin')
  log.ops.push({
    i,
    kind: 'write',
    key: step.key,
    writer: `${step.peer}#${log.incarnation[step.peer]}`,
    value: step.value,
    fileBytes: step.fileBytes ?? 0,
    sealed: epoch !== null
  })
}

const execute = async (net, step, i, log) => {
  const P = (id) => net.peers[id]
  const writer = (id) => `${id}#${log.incarnation[id]}`
  const peer = P(step.peer)
  switch (step.op) {
    case 'write':
      // A refused write (no key yet, a rotation owed) is retried after the
      // heal (retryRefused).
      try {
        await write(peer, step, i, log)
      } catch (error) {
        if (!REFUSED.test(error.message)) throw error
        peer.trace('schedule.refused', { i, message: error.message })
        log.refused.push({ i, step })
      }
      return
    case 'remove':
      await peer.remove(step.key)
      log.ops.push({
        i,
        kind: 'remove',
        key: step.key,
        writer: writer(step.peer)
      })
      return
    case 'offline':
      return peer.goOffline()
    case 'online':
      return goOnline(peer, log)
    case 'closeOpen':
      await settle(peer, log)
      await peer.closeVault()
      return peer.openVault()
    case 'restart':
      await settle(peer, log)
      return peer.restartVault()
    case 'swarmDestroy':
      peer.trace('swarm.destroy')
      await peer.instance.swarm.destroy()
      return peer.restartVault()
    case 'lock':
      await settle(peer, log)
      return peer.lock()
    case 'unlock':
      return peer.unlock()
    case 'epoch':
      return peer.ensureEpoch({ start: true })
    case 'wait':
      return sleep(step.ms)
    case 'kick':
    case 'kickLock': {
      const by = P(step.by)
      const target = P(step.target)
      await barrier(by, target)
      const seqs = await Promise.all([by, target].map((p) => p.epochStatus()))
      log.kicks.push({
        i,
        target: step.target,
        lastHeldSeq: Math.max(...seqs.map((s) => s.seq)),
        from: net.events.length
      })
      log.members.delete(step.target)
      if (step.op === 'kick') {
        await by.kick(target.deviceId)
      } else {
        const kicking = by.kick(target.deviceId).catch((error) => error)
        await sleep(5)
        await by.lock()
        await kicking
        await by.unlock()
      }
      // The kick rotated the target out.
      await holdsMembers(
        by,
        [...log.members].map((id) => P(id).deviceId).sort()
      )
      return
    }
    case 'rejoin': {
      const by = P(step.by)
      const target = P(step.target)
      log.kicks.at(-1).until = net.events.length
      if (!step.sameStore) await target.appDeps.removeVault(target.vaultId)
      let result
      try {
        result = await pairOrCancel(target, await by.invite(), {
          timeout: 30000
        })
      } finally {
        // R1: a pairing that does not resolve leaves its Autopass open.
        if (!result?.paired) {
          const pairer = target.created.findLast((c) => c.label === 'pairer')
          await pairer?.instance.pass?.close()
        }
      }
      if (!result.paired) throw result.error
      log.incarnation[step.target]++
      log.members.add(step.target)
      return
    }
  }
  throw new Error(`unknown op ${step.op}`)
}

// Per key, each writer's last op: a writer's earlier ops on the key are
// behind its later one, so the vault ends on one of these.
const lastOps = (ops) => {
  const byKey = new Map()
  for (const op of ops) {
    if (!byKey.has(op.key)) byKey.set(op.key, new Map())
    byKey.get(op.key).set(op.writer, op)
  }
  return new Map([...byKey].map(([key, m]) => [key, [...m.values()]]))
}

const show = (value) => JSON.stringify(value)

/** `get` without the file it hands back inside the value, and its size. */
const read = async (peer, key) => {
  const { file = null, ...value } = (await peer.get(key)) ?? {}
  return {
    value: Object.keys(value).length ? value : null,
    bytes: file?.length ?? file?.data?.length ?? 0
  }
}

const snapshot = async (peer, keys) => {
  const values = {}
  const files = {}
  for (const key of keys) {
    const got = await read(peer, key)
    values[key] = got.value
    files[key] = got.bytes
  }
  return {
    values,
    files,
    listed: (await peer.list('note/')).length,
    devices: (await peer.devices()).map((d) => d.id).sort()
  }
}

/** First difference between members' snapshots, or null. */
const disagreement = (members, snaps, keys) => {
  const [first, ...rest] = snaps
  for (const [j, snap] of rest.entries()) {
    const id = members[j + 1].id
    const base = members[0].id
    if (show(snap.devices) !== show(first.devices)) {
      return `device rows: ${base}=${show(first.devices)} ${id}=${show(snap.devices)}`
    }
    for (const key of keys) {
      if (show(snap.values[key]) !== show(first.values[key])) {
        return `key ${key}: ${base}=${show(first.values[key])} ${id}=${show(snap.values[key])}`
      }
      if (snap.files[key] !== first.files[key]) {
        return `file ${key}: ${base}=${first.files[key]} B ${id}=${snap.files[key]} B`
      }
    }
    if (snap.listed !== first.listed) {
      return `list note/: ${base}=${first.listed} rows ${id}=${snap.listed} rows`
    }
  }
  return null
}

/** First key the agreed snapshot gets wrong against the model, or null. */
const modelError = (snap, last, memberIds) => {
  if (show(snap.devices) !== show(memberIds)) {
    return `device rows ${show(snap.devices)}, members ${show(memberIds)}`
  }
  let present = 0
  for (const [key, ops] of last) {
    const value = snap.values[key]
    const writes = ops.filter((o) => o.kind === 'write')
    const options = ops.map((o) =>
      o.kind === 'write'
        ? `n=${o.value.n} by ${o.writer}`
        : `removed by ${o.writer}`
    )
    if (value === null) {
      if (ops.some((o) => o.kind === 'remove')) continue
      return `key ${key} lost: absent, expected one of ${options.join(', ')}`
    }
    present++
    const match = writes.find((o) => show(o.value) === show(value))
    if (!match) {
      return `key ${key} holds ${show(value)}, expected one of ${options.join(', ')}`
    }
    if (snap.files[key] !== match.fileBytes) {
      return `key ${key} file ${snap.files[key]} B, expected ${match.fileBytes} B`
    }
  }
  if (snap.listed !== present) {
    return `list note/ holds ${snap.listed} rows, ${present} keys expected`
  }
  return null
}

const parse = (value) => (typeof value === 'string' ? JSON.parse(value) : value)

/** The device ids an envelope's epoch is sealed to, read on `peer`. */
const sealedTo = async (peer, envelope) => {
  const { e } = parse(envelope)
  const row = await peer.raw(`epoch/${e}`)
  return row ? Object.keys(parse(row.value).members) : null
}

const fail = (invariant, message) => ({ invariant, message })

/**
 * What the minimiser keeps: the invariant, the first clause of the message
 * with peer and device ids and numbers stripped, and for a failed step its
 * op and peer.
 * @param {{ invariant: string, message: string }} failure
 * @param {object | null} [step] the step that failed
 */
export const signature = ({ invariant, message }, step = null) => {
  const clause = message
    .replace(/^step \d+ \([^)]*\): /, '')
    .replace(/^waitFor: /, '')
    .split(/[:(]/)[0]
    .replace(/\b(device-)?[A-D]\b/g, '#')
    .replace(/[0-9a-f]{8,}/gi, '#')
    .replace(/\d+/g, '#')
    .trim()
  const at = step
    ? ` ${step.op} ${step.peer ?? `${step.by}>${step.target}`}`
    : ''
  return `${invariant}${at}: ${clause}`
}

/**
 * Retry each refused write once on its writer, now that every peer is back.
 * Fails when the vault still refuses it while the writer reads and its base
 * is writable.
 */
const retryRefused = async (net, log, final) => {
  for (const { i, step } of log.refused) {
    if (!final.peers[step.peer].member) continue
    const peer = net.peers[step.peer]
    await waitFor(
      async () =>
        (await peer.epochStatus()).canRead && peer.instance.base.writable,
      { label: `${peer.id} reads and is writable` }
    ).catch(() => {})
    try {
      await write(peer, step, i, log)
    } catch (error) {
      if (!REFUSED.test(error.message)) throw error
      const status = await peer.epochStatus()
      if (status.canRead && !status.revoked && peer.instance.base.writable) {
        return fail(
          'refused',
          `step ${i} (${describeStep(step)}) refused again after the heal, while ${peer.id} reads epoch seq ${status.seq} and is writable: ${error.message}`
        )
      }
    }
  }
  return null
}

/** Members converge, nothing is lost, the epoch settles unaided. */
const checkConvergence = async (
  net,
  members,
  memberIds,
  last,
  final,
  timeout
) => {
  const keys = [...last.keys()].sort()
  let snaps = null
  try {
    await waitFor(
      async () => {
        snaps = await Promise.all(members.map((p) => snapshot(p, keys)))
        return (
          !disagreement(members, snaps, keys) &&
          !modelError(snaps[0], last, memberIds)
        )
      },
      { timeout, label: 'members converge on the model' }
    )
  } catch (error) {
    if (!snaps) return fail('convergence', error.message)
    const apart = disagreement(members, snaps, keys)
    if (apart) return fail('convergence', apart)
    return fail('lost-or-duplicated', modelError(snaps[0], last, memberIds))
  }
  if (final.epoch) {
    try {
      await settledUnaided(net, members, memberIds)
    } catch (error) {
      return fail('convergence', `epoch: ${error.message}`)
    }
  }
  return null
}

/**
 * While `target` is out after `kick`: of `keys`, it holds every row `member`
 * holds sealed to an epoch without it and reads none of them, and no epoch
 * row above the last seq it held gives it a key.
 */
const checkKicked = async (member, target, kick, keys) => {
  try {
    for (const key of keys) {
      const { row } = await waitFor(
        async () => {
          const [m, t] = await Promise.all([member.raw(key), target.raw(key)])
          return m?.value === t?.value && { row: m }
        },
        { label: `${target.id} holds ${member.id}'s row ${key}` }
      )
      if (!row || !isEnvelope(row.value)) continue
      const to = await sealedTo(member, row.value)
      if (!to || to.includes(target.deviceId)) continue
      await sealedFrom(target, key, show((await read(member, key)).value))
    }
    await waitFor(
      async () =>
        (await epochRows(target)).some(
          ({ record }) => Number(record?.seq) > kick.lastHeldSeq
        ),
      { label: `${target.id} holds an epoch row above seq ${kick.lastHeldSeq}` }
    )
    await noKeyAfter(target, { lastHeldSeq: kick.lastHeldSeq })
  } catch (error) {
    return fail(
      'revocation',
      `${target.id} kicked at step ${kick.i}: ${error.message}`
    )
  }
  return null
}

/**
 * A kicked device never reports a readable epoch sealed without it until it
 * pairs again, and one still out passes checkKicked.
 */
const checkRevocation = async (net, members, keys, log, final) => {
  for (const kick of log.kicks) {
    const target = net.peers[kick.target]
    const leak = net.events
      .slice(kick.from, kick.until ?? net.events.length)
      .find(
        (e) =>
          e.peer === kick.target &&
          e.event === 'epoch.status' &&
          e.epoch !== null &&
          e.canRead &&
          !e.members.includes(target.deviceId)
      )
    if (leak) {
      return fail(
        'revocation',
        `${kick.target} reported canRead on epoch ${leak.epoch} sealed to ${show(leak.members)}`
      )
    }
  }
  if (!final.kicked) return null
  return checkKicked(
    members[0],
    net.peers[final.kicked],
    log.kicks.at(-1),
    keys
  )
}

/** Every final value whose writer saw an epoch is an envelope everywhere. */
const checkPlaintext = async (members, last) => {
  for (const [key, ops] of last) {
    const { value } = await read(members[0], key)
    if (value === null) continue
    const write = ops.find(
      (o) => o.kind === 'write' && show(o.value) === show(value)
    )
    if (!write?.sealed) continue
    for (const peer of members) {
      const row = await peer.raw(key)
      if (row && !isEnvelope(row.value)) {
        return fail(
          'plaintext',
          `key ${key} (step ${write.i}, ${write.writer} under an epoch) is plaintext on ${peer.id}`
        )
      }
    }
  }
  return null
}

let runs = 0

/**
 * Run `input` (normalised first) on a fresh network: share one vault, run
 * the steps, heal every peer (online, open), check the invariants. On a
 * failure the timeline and the schedule are kept under
 * `test-artifacts/schedule/<label>/`.
 * @param {object[]} input
 * `flush: false` resumes the way the app does, without waiting for the
 * discovery round (Finding F1); `settle: false` closes without waiting for
 * the base to be writable (Finding F3). `known` is only recorded, with
 * the seed and the modes, in the trace and in `schedule.json`.
 * A failure is labelled `setup` until the vault is shared, then by the step
 * or invariant, and `heal` for anything else after the steps. A teardown
 * that fails after another failure is added to it as `teardown`.
 * @param {{ seed?: number | null, peers?: string[], label?: string, fake?: string, flush?: boolean, settle?: boolean, known?: string[], checkTimeout?: number }} [options]
 * @returns {Promise<{ ok: boolean, failure: { invariant: string, message: string, signature: string, teardown?: string } | null, timeline: string | null, schedule: string | null, steps: object[] }>}
 */
export const runSchedule = async (
  input,
  {
    seed = null,
    peers = peersOf(input),
    label = `seed-${seed}-${process.pid}-${++runs}`,
    fake = process.env.LOCKWRIGHT_SCHEDULE_FAKE,
    flush = true,
    settle = true,
    known = [],
    checkTimeout = CHECK_TIMEOUT
  } = {}
) => {
  const { steps, state: final } = simulate(input, peers)
  const log = {
    flush,
    settle,
    ops: [],
    refused: [],
    kicks: [],
    members: new Set(peers),
    incarnation: Object.fromEntries(peers.map((id) => [id, 1]))
  }
  let net = null
  let failure = null
  let phase = 'setup'
  try {
    net = await createNetwork({ peers, name: 'schedule' })
    // Not `seed`: redact() blanks any field whose name holds it.
    net.tracers[peers[0]].record('schedule.run', {
      rng: seed,
      label,
      steps: steps.length,
      flush,
      settle,
      known: known.join(',')
    })
    await shareVault(net)
    phase = 'step'
    for (const [i, step] of steps.entries()) {
      if (step.op === 'rejoin') {
        const kick = log.kicks.at(-1)
        const keys = log.ops.filter((o) => o.i > kick.i).map((o) => o.key)
        failure = await checkKicked(
          net.peers[step.by],
          net.peers[step.target],
          kick,
          [...new Set(keys)].sort()
        )
        if (failure) break
      }
      const actor = step.peer ?? step.by ?? peers[0]
      net.tracers[actor].record('schedule.step', {
        i,
        ...step,
        value: undefined
      })
      let timer
      try {
        await Promise.race([
          execute(net, step, i, log),
          new Promise((resolve, reject) => {
            timer = setTimeout(
              () => reject(new Error(`no result in ${STEP_TIMEOUT} ms`)),
              STEP_TIMEOUT
            )
          })
        ])
      } catch (error) {
        failure = fail(
          `step:${step.op}`,
          `step ${i} (${describeStep(step)}): ${error.message}`
        )
        failure.signature = signature(failure, step)
        break
      } finally {
        clearTimeout(timer)
      }
    }
    phase = 'heal'
    if (!failure && fake === 'kick' && log.kicks.length) {
      failure = fail('fake-kick', `step ${log.kicks[0].i} kicked`)
    }
    if (!failure) {
      for (const id of peers) {
        const s = final.peers[id]
        if (!s.open) await net.peers[id].unlock()
        else if (!s.online) await goOnline(net.peers[id], log)
      }
      failure = await retryRefused(net, log, final)
    }
    if (!failure) {
      const members = peers
        .filter((id) => final.peers[id].member)
        .map((id) => net.peers[id])
      const memberIds = members.map((p) => p.deviceId).sort()
      const last = lastOps(log.ops)
      const keys = [...last.keys()].sort()
      failure =
        (await checkConvergence(
          net,
          members,
          memberIds,
          last,
          final,
          checkTimeout
        )) ??
        (await checkRevocation(net, members, keys, log, final)) ??
        (await checkPlaintext(members, last))
    }
  } catch (error) {
    failure ??= fail(phase, error.message)
  }
  if (net) {
    let timer
    try {
      // A stuck vault (F3) never finishes closing: give up on it. Its
      // network stays open, so jest may not exit without --forceExit.
      await Promise.race([
        net.destroy({ keep: !!failure }),
        new Promise((resolve, reject) => {
          timer = setTimeout(
            () =>
              reject(
                new Error(
                  `teardown: no result in ${TEARDOWN_TIMEOUT} ms, the network was left open and the process may not exit`
                )
              ),
            TEARDOWN_TIMEOUT
          )
        })
      ])
    } catch (error) {
      if (failure) failure.teardown = error.message
      else {
        failure = fail(
          /^guard:/.test(error.message) ? 'guard' : 'teardown',
          error.message
        )
      }
    } finally {
      clearTimeout(timer)
    }
  }
  if (failure) failure.signature ??= signature(failure)
  let timeline = null
  let schedule = null
  if (failure && net) {
    const root = path.join(artifactsRoot(), 'schedule')
    const dir = path.join(root, slug(label))
    fs.mkdirSync(dir, { recursive: true })
    const events = path.join(dir, 'events.jsonl')
    fs.writeFileSync(events, net.events.map((e) => show(e)).join('\n') + '\n')
    timeline = writeTimeline({
      name: label,
      files: [events],
      failure: {
        messages: [
          `${failure.invariant}: ${failure.message}`,
          ...(failure.teardown ? [failure.teardown] : [])
        ]
      },
      root
    }).txt
    schedule = path.join(dir, 'schedule.json')
    fs.writeFileSync(
      schedule,
      JSON.stringify(
        {
          seed,
          peers,
          flush,
          settle,
          known,
          stepCount: steps.length,
          failure,
          steps
        },
        null,
        2
      )
    )
  }
  if (net) removeDir(net.dir)
  return { ok: !failure, failure, timeline, schedule, steps }
}

/**
 * Shrink a schedule that failed with `failure`. A candidate counts as
 * failing only when its failure has the same signature. Writes
 * `<label>.json` beside the timelines.
 * @param {object[]} steps
 * @param {{ failure: { invariant: string, signature: string }, seed?: number | null, peers?: string[], maxRuns?: number, maxMinutes?: number, flush?: boolean, settle?: boolean, known?: string[], label?: string }} options
 */
export const minimise = async (
  steps,
  {
    failure,
    seed = null,
    peers = peersOf(steps),
    maxRuns = 80,
    maxMinutes = 30,
    flush = true,
    settle = true,
    known = [],
    label = `seed-${seed}-${process.pid}-min`
  }
) => {
  const key = (c) => show(normalise(c, peers))
  const results = new Map()
  let n = 0
  const fails = async (candidate) => {
    const result = await runSchedule(normalise(candidate, peers), {
      seed,
      peers,
      flush,
      settle,
      known,
      label: `${label}-${++n}`
    })
    results.set(key(candidate), result)
    const same = !result.ok && result.failure.signature === failure.signature
    say(
      `minimise run ${n}: ${normalise(candidate, peers).length} steps, ${result.ok ? 'passed' : result.failure.signature}${same ? ' (same)' : ''}`
    )
    return same
  }
  const shrunk = await ddmin(normalise(steps, peers), fails, {
    maxRuns,
    deadline: Date.now() + maxMinutes * 60000,
    key
  })
  const minimal = normalise(shrunk.steps, peers)
  const found = results.get(key(minimal))
  const file = path.join(artifactsRoot(), 'schedule', `${slug(label)}.json`)
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(
    file,
    JSON.stringify(
      {
        seed,
        peers,
        flush,
        settle,
        known,
        stepCount: minimal.length,
        failure: found?.failure ?? failure,
        runs: shrunk.runs,
        exhausted: shrunk.exhausted,
        timeline: found?.timeline ?? null,
        steps: minimal
      },
      null,
      2
    )
  )
  say(
    `minimal schedule (${minimal.length} steps, ${shrunk.runs} runs${shrunk.exhausted ? ', budget spent' : ''}): ${file}\ntimeline: ${found?.timeline ?? 'the original run'}\n${show(minimal)}`
  )
  return { ...shrunk, steps: minimal, file, timeline: found?.timeline ?? null }
}
